-- DQL — Data Query Language

-- DQL is used to retrieve data.

-- Main command:

-- SELECT

-- Example:

SELECT * FROM Employee;

-- This displays the data.

-- You can also select specific columns:

SELECT name, salary
FROM Employee;

-- Output:

-- name   | salary
-- ---------------
-- Rahul  | 60000
-- Amit   | 50000
-- Raj    | 70000
